void OLED_WRITE(uint8_t mode,uint8_t data){
	uint8_t buf[2]={mode,data};
	LPI2C_DRV_MasterSetSlaveAddr(INST_LPI2C0, 0x3C, false);
	LPI2C_DRV_MasterSendDataBlocking (INST_LPI2C0,buf,2,true,100);
}

void OLED_INIT(void)
{
    uint8_t cmds[] =
    {
        0xAE,       // Display OFF

        0xD5, 0x80, // Set display clock divide ratio / oscillator

        0xA8, 0x3F, // Set multiplex ratio: 64

        0xD3, 0x00, // Set display offset: 0

        0x40,       // Set display start line: 0

        0xAD, 0x8B, // DC-DC control, enable charge pump

        0xA1,       // Segment remap

        0xC8,       // COM output scan direction

        0xDA, 0x12, // COM pins hardware configuration

        0x81, 0x80, // Contrast

        0xD9, 0x1F, // Pre-charge period

        0xDB, 0x40, // VCOMH deselect level

        0xA4,       // Display follows RAM

        0xA6,       // Normal display

        0xAF        // Display ON
    };

    for(uint8_t i = 0; i < sizeof(cmds); i++)
    {
        OLED_WRITE(0x00, cmds[i]);
    }
}
void OLED_SETCURSOR(int page,int column){
	OLED_WRITE(0x00,0xB0+page);
	OLED_WRITE(0x00,column & 0x0F);
	OLED_WRITE(0x00,0x10|(column >> 4));
}

void EEPROM_WRITE(uint8_t memAdres,uint8_t data[8]){

	uint8_t buf[8]={memAdres};

	for(uint8_t i=0;i<sizeof(data);i++){
		 buf[i+1]=data[i];
	}
	LPI2C_DRV_MasterSetSlaveAddr(0,0xA0,false);
	LPI2C_DRV_MasterSendDataBlocking(0,buf,8,true,100);
}

void EEPROM_READ(uint8_t memAdres, uint8_t data[8])
{
    LPI2C_DRV_MasterSendDataBlocking(
        0,
        &memAdres,
        1,
        false,
        100
    );

    LPI2C_DRV_MasterReceiveDataBlocking(
        0,
        data,
        8,
        true,
        100
    );
}

void OLED_CLEAR(void){
	for(uint8_t i=0;i<8;i++){
		OLED_SETCURSOR(i,0);
		for(uint8_t column=0;column<130;column++){
			OLED_WRITE(0x40,0x00);
		}
	}
}

void OLED_putstring(const char* str, int page, int col)
{
    while (*str)
    {
        char c = *str;

        uint8_t fontidx = c - 32;

        OLED_SETCURSOR(page,col);

        for (uint8_t i = 0; i < 5; i++)
        {
            OLED_WRITE(0x40, fontIdx[fontidx][i]);
        }

        OLED_WRITE(0x40, 0x00);       // Space gap between letters
        col += 6;
        str++;
    }
}
